package Practice1.DP;

import java.util.*;

public class maxProfitWithAtMostKTransactions {

    public int maxProfitProblem1(int[] prices) {
        int minPrice = Integer.MAX_VALUE;
        int maxProfit = 0;

        for (int i = 0; i < prices.length; i++) {
            // update minimum price so far
            minPrice = Math.min(minPrice, prices[i]);

            // calculate profit if sold today
            int profit = prices[i] - minPrice;

            // update maximum profit
            maxProfit = Math.max(maxProfit, profit);
        }

        return maxProfit;
    }
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    // dp[index][buy] -> max profit from index with buy state
    // buy = 1 → can buy
    // buy = 0 → can sell
    long[][] dp;

    private long f(int index, int buy, long[] prices, int n) {
        // Base case
        if (index == n) return 0;

        // Memo check
        if (dp[index][buy] != -1) {
            return dp[index][buy];
        }

        long profit;
        if (buy == 1) {
            // Option 1: Buy
            long buyStock = -prices[index] + f(index + 1, 0, prices, n);
            // Option 2: Skip
            long skip = f(index + 1, 1, prices, n);
            profit = Math.max(buyStock, skip);
        } else {
            // Option 1: Sell
            long sellStock = prices[index] + f(index + 1, 1, prices, n);
            // Option 2: Skip
            long skip = f(index + 1, 0, prices, n);
            profit = Math.max(sellStock, skip);
        }

        return dp[index][buy] = profit;
    }

    public long getMaximumProfit(long[] prices, int n) {
        dp = new long[n][2];

        // Initialize DP with -1
        for (int i = 0; i < n; i++) {
            dp[i][0] = dp[i][1] = -1;
        }

        return f(0, 1, prices, n);
    }
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    private int maxProfit(int i, int buyOrSell, int[] prices, int k, HashMap<String, Integer> hm) {
        if (i >= prices.length || k == 0)
            return 0;

        String key  = i + "code" + buyOrSell + "bix" + k;
        if(hm.containsKey(key)) return hm.get(key);
        int x = 0;
        if (buyOrSell == 0) {
            int buy   =  maxProfit(i + 1, 1, prices, k, hm) - prices[i];
            int noBuy =  maxProfit(i + 1, 0, prices, k, hm);
            x = Math.max(buy, noBuy);
        } else {
            int sell   = maxProfit(i + 1, 0, prices, k-1, hm) + prices[i];
            int noSell = maxProfit(i + 1, 1, prices, k, hm);
            x = Math.max(sell, noSell);
        }
        hm.put(key, x);
        return x;
    }

    public int maxProfit(int[] prices) {
        HashMap<String, Integer> hm = new HashMap<>();
        return maxProfit(0, 0, prices, 2, hm);
    }


    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    private int maxProfit(int i, int buyOrSell, int[] prices, HashMap<String, Integer> hm) {
        if (i >= prices.length) {
            return 0;
        }

        String key = i + "codebix" + buyOrSell;
        if (hm.containsKey(key)) {
            return hm.get(key);
        }

        int x = 0;

        if (buyOrSell == 0) {
            // Buy or Skip
            int buy = maxProfit(i + 1, 1, prices, hm) - prices[i];
            int noBuy = maxProfit(i + 1, 0, prices, hm);
            x = Math.max(buy, noBuy);
        } else {
            // Sell or Skip (cooldown applied on sell)
            int sell = maxProfit(i + 2, 0, prices, hm) + prices[i];
            int noSell = maxProfit(i + 1, 1, prices, hm);
            x = Math.max(sell, noSell);
        }

        hm.put(key, x);
        return x;
    }

    public int maxProfitCoolDown(int[] prices) {
        HashMap<String, Integer> hm = new HashMap<>();
        return maxProfit(0, 0, prices, hm);
    }
}
